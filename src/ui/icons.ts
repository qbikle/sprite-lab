type Rows = readonly string[];

const mirrorX = (rows: Rows): Rows => rows.map((r) => [...r].reverse().join(''));
const flipY = (rows: Rows): Rows => [...rows].reverse();
const transpose = (rows: Rows): Rows =>
  rows.map((_, x) => rows.map((r) => r[x] ?? '.').join(''));

